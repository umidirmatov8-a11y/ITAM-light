"""Localization (English / Russian).

* ``tr(text, **kw)`` - the English source string is the key; the Russian translation lives
  in :mod:`app.i18n.ru`.  Placeholders use ``str.format`` syntax.
* ``n(count, noun)`` - number + correctly declined noun ("147 events" / "147 событий").
* ``num(value)`` - locale-aware thousands separator.

Enumerated values stored in the database (severity, category, assessment, status, kind)
always stay in English and are translated only for display.  Sentences generated by the
analysis (explanations, recommendations, reasons) are produced in the language that is
active when the analysis runs.
"""

from __future__ import annotations

import locale
import os
import sys

SUPPORTED = {"en": "English", "ru": "Русский"}
_lang = "en"


def set_language(lang: str | None) -> None:
    global _lang
    _lang = lang if lang in SUPPORTED else "en"


def get_language() -> str:
    return _lang


def _catalog() -> dict[str, str]:
    if _lang == "ru":
        from app.i18n.ru import RU
        return RU
    return {}


def tr(text: str, **kwargs) -> str:
    template = _catalog().get(text, text) if _lang != "en" else text
    if kwargs:
        try:
            return template.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text.format(**kwargs)
    return template


def num(value) -> str:
    if value is None:
        return "-"
    if isinstance(value, float) and not value.is_integer():
        text = f"{value:,.1f}"
    else:
        text = f"{int(value):,}"
    return text.replace(",", " ") if _lang == "ru" else text


def _ru_form(count: int, forms: tuple[str, str, str]) -> str:
    count = abs(int(count))
    if count % 10 == 1 and count % 100 != 11:
        return forms[0]
    if 2 <= count % 10 <= 4 and not 12 <= count % 100 <= 14:
        return forms[1]
    return forms[2]


def n(count: int, noun: str) -> str:
    """'147 events' / '147 событий'. ``noun`` is the English singular key of :data:`NOUNS`."""
    entry = NOUNS.get(noun)
    if entry is None:
        return f"{num(count)} {noun if count == 1 else noun + 's'}"
    if _lang == "ru":
        return f"{num(count)} {_ru_form(count, entry[1])}"
    return f"{num(count)} {noun if count == 1 else entry[0]}"


