# Display labels for enumerated values stored in English.
_ENUM_LABELS = {
    "critical": "Critical", "high": "High", "medium": "Medium", "low": "Low", "informational": "Informational",
}


def severity_label(severity: str, upper: bool = True) -> str:
    text = tr(_ENUM_LABELS.get((severity or "").lower(), severity or ""))
    return text.upper() if upper else text


def detect_system_language() -> str:
    """Best-effort OS UI language detection (used for the first-run default)."""
    override = os.environ.get("WSA_LANGUAGE", "").lower()
    if override in SUPPORTED:
        return override
    try:
        if sys.platform == "win32":
            import ctypes
            lang_id = ctypes.windll.kernel32.GetUserDefaultUILanguage()  # type: ignore[attr-defined]
            if lang_id & 0x3FF == 0x19:  # LANG_RUSSIAN
                return "ru"
            return "en"
        value = os.environ.get("LANG") or (locale.getlocale()[0] or "")
        return "ru" if value.lower().startswith("ru") else "en"
    except Exception:
        return "en"
